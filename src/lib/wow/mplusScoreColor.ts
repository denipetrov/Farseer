/**
 * A score's colour on a season whose best score is `top`: the first band (highest first)
 * whose scaled start the score reaches; white below the last. Without a top yet (still
 * loading) the table's own 4350 is used.
 */
export function scoreColor(score: number, top: number | null | undefined): string {
  const scale = top && top > 0 ? top / REFERENCE_TOP : 1;
  for (const [from, color] of SCORE_COLORS) if (score >= from * scale) return color;
  return SCORE_COLORS[SCORE_COLORS.length - 1]![1];
}
